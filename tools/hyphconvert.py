#!/usr/bin/env python3
"""Converts TeX hyphenation patterns (hyph-utf8 format) into Vellum C++ tables.

  tools/hyphconvert.py assets/hyphenation/hyph-en-us.tex --name en_us \\
      --left 2 --right 3 -o components/vellum_core/src/hyphenation/en_us.cpp

Each pattern becomes its letters (UTF-8, '.' marks a word edge) plus one
digit per gap, sorted by letters so the device can binary-search them.
"""

import argparse
import re


def parse(path):
    text = re.sub(r"%.*", "", open(path, encoding="utf-8").read())
    patterns = re.search(r"\\patterns\s*\{(.*?)\}", text, re.S).group(1).split()
    exceptions = re.search(r"\\hyphenation\s*\{(.*?)\}", text, re.S)
    return patterns, exceptions.group(1).split() if exceptions else []


def notice(path):
    """The source's title, copyright and licence lines, which its licence asks to keep."""
    lines = []
    for line in open(path, encoding="utf-8"):
        if not line.startswith("%") or re.match(r"%\s*(changes|hyphenmins|texlive)\b", line):
            break
        lines.append("//" + line[1:].rstrip())
    return lines


def split_pattern(p):
    letters, digits = [], ["0"]
    for ch in p:
        if ch.isdigit():
            digits[-1] = ch
        else:
            letters.append(ch)
            digits.append("0")
    return "".join(letters), "".join(digits)


def c_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("patterns")
    ap.add_argument("--name", required=True)
    ap.add_argument("--left", type=int, required=True, help="fewest letters before a hyphen")
    ap.add_argument("--right", type=int, required=True, help="fewest letters after a hyphen")
    ap.add_argument("-o", "--output", required=True)
    args = ap.parse_args()

    patterns, exceptions = parse(args.patterns)
    table = sorted(split_pattern(p) for p in patterns)
    table_bytes = [(letters.encode(), digits) for letters, digits in table]
    table_bytes.sort(key=lambda t: t[0])  # the device compares raw UTF-8 bytes
    exceptions = sorted(exceptions, key=lambda w: w.replace("-", "").encode())
    source = args.patterns.split("/")[-1]

    out = [
        f"// Generated by tools/hyphconvert.py from {source}: do not edit.",
        f"// {len(table_bytes)} patterns, {len(exceptions)} exceptions.",
        "//",
        *notice(args.patterns),
        "// clang-format off",
        '#include "vellum/hyphenation.h"',
        "",
        "namespace vellum::hyphenation {",
        "namespace {",
        "",
        "constexpr HyphenPattern kPatterns[] = {",
    ]
    for letters, digits in table_bytes:
        out.append(f"    {{{c_string(letters.decode())}, {c_string(digits)}}},")
    out.append("};")
    out.append("")
    if exceptions:
        out.append("// Whole words with their hyphens, sorted without them.")
        out.append("constexpr const char* kExceptions[] = {")
        for w in exceptions:
            out.append(f"    {c_string(w)},")
        out.append("};")
    else:
        out.append("constexpr const char* const* kExceptions = nullptr;")
    out += [
        "",
        "}  // namespace",
        "",
        f"extern const Hyphenator {args.name} = {{kPatterns, {len(table_bytes)}, kExceptions, {len(exceptions)}, "
        f"{args.left}, {args.right}}};",
        "",
        "}  // namespace vellum::hyphenation",
        "// clang-format on",
    ]
    with open(args.output, "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")
    print(f"{args.output}: {len(table_bytes)} patterns, {len(exceptions)} exceptions")


if __name__ == "__main__":
    main()
