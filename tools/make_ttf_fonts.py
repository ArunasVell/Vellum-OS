#!/usr/bin/env python3
"""Embeds the built-in TrueType families that the device renders itself.

Literata comes pre-rendered (tools/make_fonts.sh). The other built-in
families are stored as font files, cut down to the reader's character set
at regular weight, and rendered on the device at whatever size is needed
(vellum/font_raster.h), which costs far less flash than every size
pre-rendered.

  pip install fonttools
  python3 tools/make_ttf_fonts.py
"""
import io
import pathlib

from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

root = pathlib.Path(__file__).resolve().parent.parent
assets = root / "assets/fonts"
out_dir = root / "components/vellum_core/src/fonts"

# Same as tools/fontconvert.py.
CHARSET = (
    list(range(0x20, 0x7F))
    + list(range(0xA0, 0x100))
    + list(range(0x100, 0x180))
    + [0x2013, 0x2014, 0x2018, 0x2019, 0x201A, 0x201C, 0x201D, 0x201E, 0x2022, 0x2026, 0x2039, 0x203A, 0x20AC]
)

FAMILIES = [
    # identifier, family name, regular file, italic file
    ("atkinson", "Atkinson Hyperlegible Next", "atkinson/AtkinsonHyperlegibleNext[wght].ttf",
     "atkinson/AtkinsonHyperlegibleNext-Italic[wght].ttf"),
    ("ebgaramond", "EB Garamond", "ebgaramond/EBGaramond[wght].ttf", "ebgaramond/EBGaramond-Italic[wght].ttf"),
]


def slim(path):
    font = TTFont(path)
    if "fvar" in font:
        axes = {a.axisTag: (400 if a.axisTag == "wght" else a.defaultValue) for a in font["fvar"].axes}
        font = instancer.instantiateVariableFont(font, axes)
    opts = subset.Options()
    opts.layout_features = ["kern"]
    opts.hinting = False
    opts.notdef_outline = True
    opts.name_IDs = [1, 2]
    opts.desubroutinize = True
    s = subset.Subsetter(opts)
    s.populate(unicodes=CHARSET)
    s.subset(font)
    buf = io.BytesIO()
    font.save(buf)
    return buf.getvalue()


def array(name, data):
    lines = [f"const uint8_t {name}[] = {{"]
    for i in range(0, len(data), 24):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i : i + 24]) + ",")
    lines.append("};")
    lines.append(f"const unsigned {name}Size = sizeof({name});")
    return lines


for ident, family, regular, italic in FAMILIES:
    reg = slim(assets / regular)
    ita = slim(assets / italic)
    out = [
        f"// Generated by tools/make_ttf_fonts.py from {regular.split('/')[-1]} and {italic.split('/')[-1]}:",
        f"// {family} (SIL Open Font License), regular weight, reader character set. Do not edit.",
        "// clang-format off",
        '#include "vellum/font_library.h"',
        "",
        "namespace vellum::fonts {",
        "",
        *array(f"k{ident.capitalize()}Regular", reg),
        "",
        *array(f"k{ident.capitalize()}Italic", ita),
        "",
        "}  // namespace vellum::fonts",
        "// clang-format on",
        "",
    ]
    path = out_dir / f"{ident}_ttf.cpp"
    path.write_text("\n".join(out))
    print(f"wrote {path.relative_to(root)}: {len(reg)} + {len(ita)} bytes")
