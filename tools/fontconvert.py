#!/usr/bin/env python3
"""Converts a TrueType font into a Vellum bitmap font (generated C++ source).

Glyphs are rendered once, on the build machine, with FreeType (light hinting)
and stored as 2-bit coverage, so the device only copies pixels. Advances and
kerning come from HarfBuzz, so they match what a full shaper would produce.

  pip install freetype-py uharfbuzz
  tools/fontconvert.py FONT.ttf --size 30 --name literata_30 \
      --axis wght=400 -o components/vellum_core/src/fonts/literata_30.cpp

Variable fonts take --axis TAG=VALUE; opsz defaults to the size in points on
the X4 Pro's 217 ppi screen.
"""

import argparse
import sys

import freetype
import uharfbuzz as hb

PPI = 217

# Latin-1, Latin Extended-A (Lithuanian, Polish, Czech, ...), Cyrillic for Ukrainian and
# typographic punctuation.
CHARSET = (
    list(range(0x20, 0x7F))
    + list(range(0xA0, 0x100))
    + list(range(0x100, 0x180))
    + list(range(0x400, 0x460))  # Cyrillic: Ukrainian
    + [0x490, 0x491]
    + [0x2013, 0x2014, 0x2018, 0x2019, 0x201A, 0x201C, 0x201D, 0x201E, 0x2022, 0x2026, 0x2039, 0x203A, 0x20AC]
)
# Kerning smaller than this is dropped to keep the tables small.
KERN_MIN_26_6 = 32  # half a pixel


def parse_axes(items):
    axes = {}
    for item in items:
        tag, _, value = item.partition("=")
        axes[tag] = float(value)
    return axes


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("font")
    ap.add_argument("--size", type=int, required=True, help="pixel size (em height)")
    ap.add_argument("--name", required=True, help="C++ identifier of the font")
    ap.add_argument("--axis", action="append", default=[], help="variation axis, e.g. wght=400")
    ap.add_argument("-o", "--output", required=True)
    args = ap.parse_args()

    axes = parse_axes(args.axis)

    face = freetype.Face(args.font)
    blob = hb.Blob.from_file_path(args.font)
    hb_face = hb.Face(blob)
    hb_font = hb.Font(hb_face)

    if face.has_multiple_masters:
        info = face.get_variation_info()
        tags = [a.tag for a in info.axes]
        if "opsz" in tags and "opsz" not in axes:
            axes["opsz"] = args.size * 72.0 / PPI
        coords = []
        for a in info.axes:
            v = axes.get(a.tag, a.default)
            coords.append(min(max(v, a.minimum), a.maximum))
        face.set_var_design_coords(coords)
        hb_font.set_variations({a.tag: c for a, c in zip(info.axes, coords)})
        axes = {a.tag: c for a, c in zip(info.axes, coords)}

    face.set_pixel_sizes(0, args.size)
    scale = args.size * 64  # HarfBuzz positions in 26.6 pixels
    hb_font.scale = (scale, scale)

    ascent = (face.size.ascender + 63) >> 6
    descent = (-face.size.descender + 63) >> 6
    line_height = (face.size.height + 63) >> 6

    def shape(text):
        buf = hb.Buffer()
        buf.add_str(text)
        buf.guess_segment_properties()
        hb.shape(hb_font, buf, {"liga": False, "kern": True})
        return buf.glyph_positions

    glyphs = []
    bitmap = bytearray()
    for cp in CHARSET:
        if face.get_char_index(cp) == 0:
            continue
        face.load_char(cp, freetype.FT_LOAD_RENDER | freetype.FT_LOAD_TARGET_LIGHT)
        g = face.glyph
        bm = g.bitmap
        w, h = bm.width, bm.rows
        offset = len(bitmap)
        acc = 0
        nbits = 0
        for y in range(h):
            row = bm.buffer[y * bm.pitch : y * bm.pitch + w]
            for v in row:
                acc = (acc << 2) | (v >> 6)
                nbits += 2
                if nbits == 8:
                    bitmap.append(acc)
                    acc = 0
                    nbits = 0
        if nbits:
            bitmap.append(acc << (8 - nbits))
        advance = shape(chr(cp))[0].x_advance
        if w > 255 or h > 255 or not (-128 <= g.bitmap_left <= 127) or not (-128 <= g.bitmap_top <= 127):
            sys.exit(f"glyph U+{cp:04X} too large for the format")
        glyphs.append((cp, offset, w, h, g.bitmap_left, g.bitmap_top, advance))

    index = {cp: i for i, (cp, *_) in enumerate(glyphs)}
    advances = {cp: adv for cp, *_, adv in glyphs}

    kerned = [cp for cp in index if chr(cp).isalnum() or chr(cp) in ".,;:!?'\"-()[]«»‘’‚“”„–—…"]
    kerns = []
    for a in kerned:
        for b in kerned:
            pos = shape(chr(a) + chr(b))
            if len(pos) != 2:
                continue
            k = pos[0].x_advance - advances[a]
            if abs(k) >= KERN_MIN_26_6:
                kerns.append((index[a], index[b], k))
    kerns.sort()

    fallback = index.get(ord("?"), 0)
    axis_note = ", ".join(f"{t}={v:g}" for t, v in axes.items()) or "static"
    font_name = face.family_name.decode() if isinstance(face.family_name, bytes) else face.family_name

    out = []
    out.append(f"// Generated by tools/fontconvert.py from {args.font.split('/')[-1]}: do not edit.")
    out.append(f"// {font_name} {args.size} px ({axis_note}), {len(glyphs)} glyphs, {len(kerns)} kerning pairs.")
    out.append("// clang-format off")
    out.append('#include "vellum/fonts.h"')
    out.append("")
    out.append("namespace vellum::fonts {")
    out.append("namespace {")
    out.append("")
    out.append("constexpr uint8_t kBitmap[] = {")
    for i in range(0, len(bitmap), 24):
        out.append("    " + ", ".join(f"0x{b:02x}" for b in bitmap[i : i + 24]) + ",")
    out.append("};")
    out.append("")
    out.append("constexpr Glyph kGlyphs[] = {")
    for cp, off, w, h, left, top, adv in glyphs:
        out.append(f"    {{0x{cp:04x}, {off}, {w}, {h}, {left}, {top}, {adv}}},")
    out.append("};")
    out.append("")
    if kerns:
        out.append("constexpr KernPair kKerning[] = {")
        for i in range(0, len(kerns), 6):
            out.append("    " + " ".join(f"{{{a}, {b}, {k}}}," for a, b, k in kerns[i : i + 6]))
        out.append("};")
    else:
        out.append("constexpr const KernPair* kKerning = nullptr;")
    out.append("")
    out.append("}  // namespace")
    out.append("")
    out.append(f"extern const Font {args.name} = {{")
    out.append(f'    "{font_name}", {args.size}, {ascent}, {descent}, {line_height},')
    out.append(f"    kGlyphs, {len(glyphs)}, kBitmap, kKerning, {len(kerns)}, {fallback},")
    out.append("};")
    out.append("")
    out.append("}  // namespace vellum::fonts")
    out.append("// clang-format on")
    with open(args.output, "w") as f:
        f.write("\n".join(out) + "\n")
    print(f"{args.output}: {len(glyphs)} glyphs, {len(bitmap)} bitmap bytes, {len(kerns)} kerning pairs")


if __name__ == "__main__":
    main()
