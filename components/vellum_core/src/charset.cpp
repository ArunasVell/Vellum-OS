constexpr uint32_t kReplacement = 0xFFFD;

const uint16_t* table_of(Encoding e) {
  switch (e) {
    case Encoding::Windows1257:
      return kWindows1257;
    case Encoding::Windows1252:
      return kWindows1252;
    case Encoding::Iso8859_13:
      return kIso8859_13;
    case Encoding::Windows1251:
      return kWindows1251;
    default:
      return nullptr;
  }
}

// Length of the valid UTF-8 sequence at s[i] (1-4), 0 when it is malformed,
// or -1 when it is cut off by the end of the data.
int utf8_sequence(const uint8_t* s, uint32_t len, uint32_t i, uint32_t& cp) {
  const uint8_t c = s[i];
  if (c < 0x80) {
    cp = c;
    return 1;
  }
  int n;
  uint32_t min;
  if ((c & 0xE0) == 0xC0) {
    n = 2, cp = c & 0x1F, min = 0x80;
  } else if ((c & 0xF0) == 0xE0) {
    n = 3, cp = c & 0x0F, min = 0x800;
  } else if ((c & 0xF8) == 0xF0) {
    n = 4, cp = c & 0x07, min = 0x10000;
  } else {
    return 0;
  }
  for (int k = 1; k < n; ++k) {
    if (i + k >= len) return -1;
    if ((s[i + k] & 0xC0) != 0x80) return 0;
    cp = cp << 6 | (s[i + k] & 0x3F);
  }
  if (cp < min || cp > 0x10FFFF || (cp >= 0xD800 && cp <= 0xDFFF)) return 0;
  return n;
}

char lower(char c) { return (c >= 'A' && c <= 'Z') ? static_cast<char>(c + 32) : c; }

// Whether `name` equals one of the '|'-separated names in `list`, ignoring
// case, '-' and '_'.
bool name_in(std::string_view name, std::string_view list) {
  char clean[24];
  size_t n = 0;
  for (char c : name) {
    if (c == '-' || c == '_' || c == ' ') continue;
    if (n + 1 >= sizeof(clean)) return false;
    clean[n++] = lower(c);
  }
  const std::string_view want(clean, n);
  while (!list.empty()) {
    const size_t bar = list.find('|');
    if (list.substr(0, bar) == want) return true;
    list = bar == std::string_view::npos ? std::string_view{} : list.substr(bar + 1);
  }
  return false;
}

