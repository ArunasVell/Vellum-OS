Encoding detect(const uint8_t* data, uint32_t len, uint32_t& bom) {
  bom = 0;
  if (len >= 3 && data[0] == 0xEF && data[1] == 0xBB && data[2] == 0xBF) {
    bom = 3;
    return Encoding::Utf8;
  }
  if (len >= 2 && data[0] == 0xFF && data[1] == 0xFE) {
    bom = 2;
    return Encoding::Utf16LE;
  }
  if (len >= 2 && data[0] == 0xFE && data[1] == 0xFF) {
    bom = 2;
    return Encoding::Utf16BE;
  }
  // UTF-16 without a mark: most Latin text has a zero in every other byte.
  uint32_t zero_even = 0, zero_odd = 0;
  for (uint32_t i = 0; i < len; ++i) (i % 2 ? zero_odd : zero_even) += data[i] == 0;
  if (len >= 16 && zero_odd > len / 4 && zero_even * 64 <= len) return Encoding::Utf16LE;
  if (len >= 16 && zero_even > len / 4 && zero_odd * 64 <= len) return Encoding::Utf16BE;

  bool utf8 = true;
  uint32_t high = 0;  // bytes 0x80 and up
  for (uint32_t i = 0; i < len;) {
    uint32_t cp;
    const int n = utf8_sequence(data, len, i, cp);
    if (n < 0) break;  // cut off by the end of the sample
    if (n == 0) {
      utf8 = false;
      ++high;
      break;
    }
    high += n > 1;
    i += static_cast<uint32_t>(n);
  }
  if (utf8 || high == 0) return Encoding::Utf8;

  // A one-byte code page. Lithuanian in Windows-1257 is full of š, ž and ė
  // (bytes that are the rare ð, þ and ë in Western code pages).
  uint32_t baltic = 0, letters = 0, c1 = 0, latin_quotes = 0;
  for (uint32_t i = 0; i < len; ++i) {
    const uint8_t c = data[i];
    if (c >= 0xC0) ++letters;
    if (c == 0xF0 || c == 0xD0 || c == 0xFE || c == 0xDE || c == 0xEB || c == 0xCB) ++baltic;
    if (c >= 0x80 && c < 0xA0) ++c1;
    if (c == 0xA1 || c == 0xA5 || c == 0xB4) ++latin_quotes;  // ” „ “ in ISO-8859-13
  }
  if (baltic > 0 && baltic * 5 >= letters) {
    // ISO-8859-13 has no characters at 0x80..0x9F and puts its quotes higher.
    return c1 == 0 && latin_quotes > 0 ? Encoding::Iso8859_13 : Encoding::Windows1257;
  }
  return Encoding::Windows1252;
}

bool from_name(std::string_view name, Encoding& out) {
  if (name_in(name, "utf8")) {
    out = Encoding::Utf8;
  } else if (name_in(name, "utf16le|utf16")) {
    out = Encoding::Utf16LE;
  } else if (name_in(name, "utf16be")) {
    out = Encoding::Utf16BE;
  } else if (name_in(name, "windows1257|cp1257")) {
    out = Encoding::Windows1257;
  } else if (name_in(name, "windows1252|cp1252|usascii|ascii")) {
    out = Encoding::Windows1252;
  } else if (name_in(name, "iso885913|latin7")) {
    out = Encoding::Iso8859_13;
  } else if (name_in(name, "windows1251|cp1251")) {
    out = Encoding::Windows1251;
  } else if (name_in(name, "iso88591|latin1")) {
    out = Encoding::Latin1;
  } else {
    return false;
  }
  return true;
}

uint32_t to_utf8(Encoding e, const uint8_t* in, uint32_t len, char* out, uint32_t cap) {
  uint32_t w = 0;
  auto put = [&](uint32_t cp) {
    char buf[4];
    const size_t n = xml::encode_utf8(cp, buf);
    if (w + n > cap) return false;
    for (size_t k = 0; k < n; ++k) out[w++] = buf[k];
    return true;
  };
  if (e == Encoding::Utf8) {
    for (uint32_t i = 0; i < len;) {
      if (in[i] < 0x80) {
        if (w >= cap) break;
        out[w++] = static_cast<char>(in[i++]);
        continue;
      }
      uint32_t cp;
      const int n = utf8_sequence(in, len, i, cp);
      if (n < 0) break;
      if (!put(n == 0 ? kReplacement : cp)) break;
      i += n == 0 ? 1 : static_cast<uint32_t>(n);
    }
  } else if (e == Encoding::Utf16LE || e == Encoding::Utf16BE) {
    const bool le = e == Encoding::Utf16LE;
    auto at = [&](uint32_t i) { return static_cast<uint32_t>(le ? in[i] | in[i + 1] << 8 : in[i] << 8 | in[i + 1]); };
    for (uint32_t i = 0; i + 1 < len; i += 2) {
      uint32_t cp = at(i);
      if (cp >= 0xD800 && cp < 0xDC00) {
        if (i + 3 >= len) break;  // the pair is cut off
        const uint32_t lo = at(i + 2);
        if (lo >= 0xDC00 && lo < 0xE000) {
          cp = 0x10000 + ((cp - 0xD800) << 10) + (lo - 0xDC00);
          i += 2;
        } else {
          cp = kReplacement;
        }
      } else if (cp >= 0xDC00 && cp < 0xE000) {
        cp = kReplacement;
      }
      if (!put(cp)) break;
    }
  } else {
    const uint16_t* table = table_of(e);
    for (uint32_t i = 0; i < len; ++i) {
      const uint8_t c = in[i];
      if (!put(c < 0x80 || table == nullptr ? c : table[c - 0x80])) break;
    }
  }
  return w;
}

uint32_t code_point(Encoding e, uint8_t byte) {
  const uint16_t* table = table_of(e);
  return byte < 0x80 || table == nullptr ? byte : table[byte - 0x80];
}

